//! Language module architecture and registry (issue #62).
//!
//! Language modules provide task-scoped environment provisioning, specialized tool sets,
//! tailored prompt guidelines, and verification checks for specific programming languages.

use std::collections::HashMap;
use std::path::Path;
use std::sync::{Arc, PoisonError, RwLock};

pub use nebula_proto::{
    LanguageInfoParams, LanguageInfoResponse, LanguageListResponse, LanguageMetadata,
};
use nebula_proto::{TaskId, TraceId};
use nebula_sandbox::task_job::TaskJob;
use nebula_tools::BuiltinTool;
use serde::{Deserialize, Serialize};
use serde_json::Value;

pub mod polyglot;
pub use polyglot::PolyglotModule;

/// The environment and configuration context passed during module provisioning.
pub struct ProvisionContext<'a> {
    /// The unique task ID.
    pub task_id: &'a TaskId,
    /// The root path of the isolated task worktree.
    pub worktree_root: &'a Path,
    /// Optional Windows Job Object wrapping task child processes.
    pub task_job: Option<&'a Arc<TaskJob>>,
    /// Optional module-specific configuration options from [`nebula_proto::TaskCreateParams`].
    pub language_config: Option<&'a Value>,
    /// Distributed trace ID for the task.
    pub trace_id: &'a TraceId,
}

/// Verification report returned when a language module finishes final checks.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FinalizeReport {
    /// Whether final language verification/checks succeeded.
    pub success: bool,
    /// Human-readable summary of actions taken and results.
    pub summary: String,
    /// Artifacts or report paths generated by the finalizer.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub artifacts: Vec<String>,
}

/// Errors occurring within language module lifecycle hooks.
#[derive(Debug, thiserror::Error)]
pub enum LanguageError {
    /// Environment provisioning failed.
    #[error("provisioning failed: {0}")]
    ProvisionFailed(String),
    /// Post-task finalization / verification failed.
    #[error("finalization failed: {0}")]
    FinalizeFailed(String),
    /// A module-specific tool failed during execution.
    #[error("tool execution failed: {0}")]
    ToolFailed(String),
    /// The requested runtime version is unsupported.
    #[error("unsupported version: {0}")]
    UnsupportedVersion(String),
    /// Invalid module configuration.
    #[error("configuration error: {0}")]
    Config(String),
    /// Other module error.
    #[error("{0}")]
    Other(String),
}

/// Asynchronous trait defining a language module lifecycle.
#[async_trait::async_trait]
pub trait LanguageModule: Send + Sync {
    /// Unique identifier of the language module (e.g. "python", "cpp", "sql", "polyglot").
    fn id(&self) -> &str;

    /// Return metadata describing the module.
    fn metadata(&self) -> LanguageMetadata;

    /// Check if the target repository/worktree matches this language.
    /// Returns confidence score 0.0 ..= 1.0 (or None if no match).
    async fn detect(&self, repo_root: &Path) -> Option<f32>;

    /// Provision hermetic environment (e.g. .venv, build cache) in worktree.
    async fn provision(&self, ctx: &ProvisionContext<'_>) -> Result<(), LanguageError>;

    /// Return the list of tools provided by this module for the task.
    fn tools(&self) -> Vec<Arc<dyn BuiltinTool>>;

    /// System prompt instructions and constraints specific to this language module.
    fn prompt_guidelines(&self, ctx: &ProvisionContext<'_>) -> Vec<String>;

    /// Run post-task verification (formatting, lockfile cleanup, final tests).
    async fn finalize(&self, ctx: &ProvisionContext<'_>) -> Result<FinalizeReport, LanguageError>;

    /// Optional hook called when inference is paused (e.g. during Game Mode).
    async fn on_pause(&self) {}

    /// Optional hook called when inference resumes after pause.
    async fn on_resume(&self) {}
}

/// Thread-safe registry of available language modules.
pub struct LanguageRegistry {
    modules: RwLock<HashMap<String, Arc<dyn LanguageModule>>>,
}

impl LanguageRegistry {
    /// Create an empty language registry.
    #[must_use]
    pub fn new() -> Self {
        Self {
            modules: RwLock::new(HashMap::new()),
        }
    }

    /// Create a language registry initialized with default modules (`PolyglotModule`).
    #[must_use]
    pub fn with_defaults() -> Self {
        let registry = Self::new();
        registry.register(Arc::new(PolyglotModule));
        registry
    }

    /// Register a language module. Overwrites existing module with same ID if present.
    pub fn register(&self, module: Arc<dyn LanguageModule>) {
        let mut lock = self.modules.write().unwrap_or_else(PoisonError::into_inner);
        lock.insert(module.id().to_string(), module);
    }

    /// Notify all registered modules that inference has been paused.
    pub async fn on_pause(&self) {
        let modules: Vec<Arc<dyn LanguageModule>> = self
            .modules
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .values()
            .cloned()
            .collect();
        for module in modules {
            module.on_pause().await;
        }
    }

    /// Notify all registered modules that inference has resumed.
    pub async fn on_resume(&self) {
        let modules: Vec<Arc<dyn LanguageModule>> = self
            .modules
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .values()
            .cloned()
            .collect();
        for module in modules {
            module.on_resume().await;
        }
    }

    /// Get a registered language module by ID.
    #[must_use]
    pub fn get(&self, id: &str) -> Option<Arc<dyn LanguageModule>> {
        let lock = self.modules.read().unwrap_or_else(PoisonError::into_inner);
        lock.get(id).cloned()
    }

    /// Return metadata for all registered language modules, sorted by ID.
    #[must_use]
    pub fn list(&self) -> Vec<LanguageMetadata> {
        let lock = self.modules.read().unwrap_or_else(PoisonError::into_inner);
        let mut list: Vec<LanguageMetadata> = lock.values().map(|m| m.metadata()).collect();
        list.sort_by(|a, b| a.id.cmp(&b.id));
        list
    }

    /// Auto-detect the best language module for a given repository.
    ///
    /// Iterates through registered modules and selects the one with the highest confidence score > 0.0.
    pub async fn detect(&self, repo_root: &Path) -> Option<Arc<dyn LanguageModule>> {
        let modules: Vec<Arc<dyn LanguageModule>> = {
            let lock = self.modules.read().unwrap_or_else(PoisonError::into_inner);
            lock.values().cloned().collect()
        };

        let mut best: Option<(Arc<dyn LanguageModule>, f32)> = None;
        for module in modules {
            if let Some(score) = module.detect(repo_root).await
                && score > 0.0
                && best.as_ref().is_none_or(|(_, s)| score > *s)
            {
                best = Some((module.clone(), score));
            }
        }
        best.map(|(m, _)| m)
    }
}

impl Default for LanguageRegistry {
    fn default() -> Self {
        Self::with_defaults()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct MockPythonModule;

    #[async_trait::async_trait]
    impl LanguageModule for MockPythonModule {
        fn id(&self) -> &str {
            "python"
        }

        fn metadata(&self) -> LanguageMetadata {
            LanguageMetadata {
                id: "python".into(),
                display_name: "Python (uv-managed)".into(),
                description: "Python test module".into(),
                supported_versions: vec!["3.11".into(), "3.12".into()],
                default_version: Some("3.12".into()),
            }
        }

        async fn detect(&self, repo_root: &Path) -> Option<f32> {
            if repo_root.join("pyproject.toml").exists() {
                Some(0.9)
            } else {
                None
            }
        }

        async fn provision(&self, _ctx: &ProvisionContext<'_>) -> Result<(), LanguageError> {
            Ok(())
        }

        fn tools(&self) -> Vec<Arc<dyn BuiltinTool>> {
            Vec::new()
        }

        fn prompt_guidelines(&self, _ctx: &ProvisionContext<'_>) -> Vec<String> {
            vec!["Use pytest for tests".into()]
        }

        async fn finalize(
            &self,
            _ctx: &ProvisionContext<'_>,
        ) -> Result<FinalizeReport, LanguageError> {
            Ok(FinalizeReport {
                success: true,
                summary: "Python tests passed".into(),
                artifacts: vec!["pytest.xml".into()],
            })
        }
    }

    #[tokio::test]
    async fn registry_registers_and_retrieves_module() {
        let registry = LanguageRegistry::with_defaults();
        assert!(registry.get("polyglot").is_some());
        assert!(registry.get("python").is_none());

        registry.register(Arc::new(MockPythonModule));
        assert!(registry.get("python").is_some());

        let list = registry.list();
        assert_eq!(list.len(), 2);
        assert_eq!(list[0].id, "polyglot");
        assert_eq!(list[1].id, "python");
    }

    #[tokio::test]
    async fn registry_detects_highest_scoring_module() {
        let registry = LanguageRegistry::with_defaults();
        registry.register(Arc::new(MockPythonModule));

        let tmp = tempfile::tempdir().unwrap();
        // Without pyproject.toml, falls back to polyglot (0.1)
        let detected = registry.detect(tmp.path()).await.unwrap();
        assert_eq!(detected.id(), "polyglot");

        // With pyproject.toml, python module scores 0.9 > 0.1
        std::fs::write(tmp.path().join("pyproject.toml"), "").unwrap();
        let detected = registry.detect(tmp.path()).await.unwrap();
        assert_eq!(detected.id(), "python");
    }

    #[tokio::test]
    async fn polyglot_module_lifecycle() {
        let poly = PolyglotModule;
        assert_eq!(poly.id(), "polyglot");
        assert_eq!(poly.metadata().id, "polyglot");
        assert!(poly.tools().is_empty());

        let task_id = TaskId::new();
        let trace_id = TraceId::new();
        let tmp = tempfile::tempdir().unwrap();
        let ctx = ProvisionContext {
            task_id: &task_id,
            worktree_root: tmp.path(),
            task_job: None,
            language_config: None,
            trace_id: &trace_id,
        };

        poly.provision(&ctx).await.unwrap();
        assert!(poly.prompt_guidelines(&ctx).is_empty());
        let report = poly.finalize(&ctx).await.unwrap();
        assert!(report.success);
    }
}
